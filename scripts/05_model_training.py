# TRAINING FUNCTIONS
# ============================================================================
def final_training(best_params, train_files, y_all):
    """
    Train the final model with standard full-data gradient boosting.

    Builds ONE QuantileDMatrix by streaming every training chunk through
    lib.xgb_data (the full ~100 GB sparse matrix is never materialised in RAM;
    binary data + max_bin=2 keep the quantised matrix to ~1 byte per non-zero),
    then boosts the Optuna-tuned number of trees over it.

    This replaces the legacy 1-tree-per-chunk incremental regime, where each tree
    saw only a single ~200-genome slice — weaker fit and very low CPU efficiency
    on HPC. Full-data boosting gives every tree the whole training set and uses
    all allocated cores.

    Class imbalance is corrected ONCE here via a single global neg/pos instance
    weight on positive rows (04's HPO intentionally leaves scale_pos_weight
    untuned to avoid double-counting the correction).

    Args:
        best_params: XGBoost hyperparameters dictionary (incl. n_estimators).
        train_files: List of paths to matrix chunk files.
        y_all: Complete label array.

    Returns:
        tuple: (Trained XGBoost Booster model, optimal_threshold)
    """
    print("\n" + "=" * 80)
    print("FULL-DATA GRADIENT BOOSTING (streaming QuantileDMatrix)")
    print("=" * 80)

    # Guard against a degenerate tuned budget (0 or missing): always at least one
    # tree so the model is never left as None.
    total_trees = max(1, int(best_params.pop('n_estimators', 100)))

    params = best_params.copy()
    # Imbalance is handled by the global instance weight below, so drop any
    # scale_pos_weight to avoid double-counting the correction.
    params.pop('scale_pos_weight', None)
    # Pin base_score to the neutral 0.5 (XGBoost >= 2.0 otherwise derives the
    # intercept from the weighted label mean; pinning keeps runs reproducible and
    # avoids the "base_score must be in (0,1)" edge case on skewed weights).
    params.setdefault('base_score', 0.5)
    max_bin = int(params.get('max_bin', 2))

    # Single global neg/pos weight (replaces per-chunk dynamic instance weighting,
    # which only made sense when each tree trained on one chunk in isolation).
    pos_weight = global_pos_weight(train_files, y_all, CHUNK_SIZE)
    print(f"Target trees (Optuna): {total_trees} | global pos weight (neg/pos): {pos_weight:.3f}")
    print(f"Streaming {len(train_files)} chunks into an ExtMemQuantileDMatrix (max_bin={max_bin})...")

    # External memory: the full train matrix is too large to hold in-core (the
    # ~109 GB sparse matrix peaks >400 GB as a plain QuantileDMatrix, OOM-killing
    # a 384 GB node). Spill quantised pages to fast scratch instead; RAM then
    # stays bounded to ~one page + histograms. Cache lives next to the model and
    # is removed after training.
    cache_dir = MODELS_DIR / "_xgb_cache_train"
    shutil.rmtree(cache_dir, ignore_errors=True)
    cache_dir.mkdir(parents=True, exist_ok=True)
    cache_prefix = str(cache_dir / "cache")
    dtrain = None
    try:
        dtrain = build_quantile_dmatrix(train_files, y_all, CHUNK_SIZE,
                                        max_bin=max_bin, pos_weight=pos_weight,
                                        cache_prefix=cache_prefix)
        print(f"  ✓ DMatrix built: {dtrain.num_row():,} rows × {dtrain.num_col():,} features")

        model = xgb.train(params, dtrain, num_boost_round=total_trees)
        print(f"  ✓ Trained {model.num_boosted_rounds()} trees over the full training set.")
    finally:
        dtrain = None              # release the DMatrix so its cache files unlock
        gc.collect()
        shutil.rmtree(cache_dir, ignore_errors=True)

    # Global class weighting is active → the operating threshold stays the neutral
    # 0.5. It is NOT tuned on the test set (P-01 leakage fix); 06 only reports
    # Youden's J and never overwrites this value.
    optimal_threshold = 0.5
    print("\n[Threshold Configuration]")
    print(f"  Operating threshold fixed at {optimal_threshold:.4f} "
          f"(global class weighting; no test-set tuning).")

    return model, optimal_threshold


def final_test(model, test_files, y_all, optimal_threshold):
    """
    Evaluate model on test set using the unbiased Optimal Threshold.
    
    CRITICAL (Data Leakage Prevention):
    We do NOT optimize the threshold using the Test Set. Doing so (e.g., trying
    0.1 to 0.9 and picking the highest MCC on the test set) causes data leakage
    and artificially inflates evaluation metrics off completely unseen data.
    Instead, we use the `optimal_threshold` calculated purely from the 
    Training Set's class prevalence (Resistance Ratio).
    
    Args:
        model: Trained XGBoost model
        test_files: List of test chunk file paths
        y_all: Complete label array
        optimal_threshold: The unbiased threshold calculated from training prevalence
    
    Returns:
        None (prints evaluation metrics)
    """
    print("\n" + "=" * 80)
    print("MODEL EVALUATION (UNBIASED TEST SET)")
    print("=" * 80)
    
    y_true_all = []
    y_prob_all = []
    
    print("Generating predictions...")
    
    for chunk_file in test_files:
        try:
            X_chunk = load_npz(chunk_file)
            chunk_num = int(chunk_file.stem.split('_')[-1])
            y_chunk = get_y_chunk(y_all, chunk_num, CHUNK_SIZE, len(y_all))
            
            dtest = xgb.DMatrix(X_chunk, nthread=-1)
            probs = model.predict(dtest)
            
            y_true_all.extend(y_chunk)
            y_prob_all.extend(probs)
            
            del X_chunk, dtest
            gc.collect()
            
        except Exception as e:
            print(f"ERROR: {e}")
            sys.exit(1)
    
    y_true_all = np.array(y_true_all)
    y_prob_all = np.array(y_prob_all)
    
    # Threshold application without peeking at test results (No Data Leakage)
    print(f"\nApplying Unbiased Treshold: {optimal_threshold:.4f} (from Training Distribution)")
    
    y_pred_all = (y_prob_all >= optimal_threshold).astype(int)
    
    # Performance metrics using unbiased prediction
    acc = accuracy_score(y_true_all, y_pred_all)
    auc = roc_auc_score(y_true_all, y_prob_all)
    final_mcc = matthews_corrcoef(y_true_all, y_pred_all)
    
    print("\n" + "=" * 80)
    print("PERFORMANCE METRICS")
    print("=" * 80)
    print(f"Accuracy    : {acc:.4f}")
    print(f"ROC AUC     : {auc:.4f}")
    print(f"MCC         : {final_mcc:.4f}")
    print(f"Threshold   : {optimal_threshold:.4f}")
    print("=" * 80)
    
    print("\nClassification Report:")
    print(classification_report(y_true_all, y_pred_all, 
                                target_names=['Susceptible', 'Resistant'], 
                                digits=4))
    
    print("Confusion Matrix:")
    cm = confusion_matrix(y_true_all, y_pred_all)
    print(cm)
    print("\n" + "=" * 80)

    return {
        'accuracy': float(acc),
        'roc_auc': float(auc),
        'mcc': float(final_mcc),
        'threshold': float(optimal_threshold),
        'n_test_samples': int(len(y_true_all)),
    }


# ============================================================================
# MAIN PIPELINE
# ============================================================================
def main():
    """
    Execute complete training and evaluation pipeline.
    
    Steps:
        1. Load optimized hyperparameters and data split from antibiotic-specific config
        2. Load labels and resolve chunk file paths
        3. Use stratified train/test split from optimization (NO randomization)
        4. Train model incrementally on exact training chunks
        5. Evaluate on exact test chunks (same as optimization)
        6. Save trained model
    """
    print("=" * 80)
    print(f"XGBoost TRAINING - {TARGET_ANTIBIOTIC.upper()} RESISTANCE PREDICTION")
    print("=" * 80)
    
    # Load optimized hyperparameters and data split
    print("\n[1/5] Loading optimized hyperparameters and data split...")
    print("=" * 80)
    
    try:
        best_params, train_filenames, test_filenames = load_optimized_hyperparameters()
        print("=" * 80)
    except FileNotFoundError as e:
        print(f"ERROR: {e}")
        sys.exit(1)
    
    # Load data
    print("\n[2/5] Loading labels and discovering chunk files...")
    
    try:
        y_path = MATRIX_DIR / f"y_{TARGET_ANTIBIOTIC}.csv"
        if not y_path.exists():
            raise FileNotFoundError(f"Label file not found: {y_path}")
        
        y_all = pd.read_csv(y_path, encoding='utf-8')['label'].values
        
        all_files = list(MATRIX_DIR.glob(f"X_{TARGET_ANTIBIOTIC}_part_*.npz"))
        if not all_files:
            raise FileNotFoundError("No matrix chunks found")
        
        print(f"  ✓ Loaded {len(y_all)} labels, {len(all_files)} chunks")
        
    except FileNotFoundError as e:
        print(f"ERROR: {e}")
        sys.exit(1)
    
    # Use train/test split from config (reproducible, stratified)
    print("\n[3/5] Loading stratified train/test split from config...")
    
    # Load antibiotic-specific config to show optuna subset info
    try:
        antibiotic_config_path = resolve_path('experiment_config', organism=ORGANISM,
                                              antibiotic=TARGET_ANTIBIOTIC, config=config)
        with open(antibiotic_config_path, 'r') as f:
            antibiotic_config = yaml.safe_load(f)
        optuna_count = antibiotic_config.get('data_split', {}).get('optuna_count', 'N/A')
    except Exception:
        optuna_count = 'N/A'
    
    # Create filename -> path mapping
    file_map = {f.name: f for f in all_files}
    
    # Resolve train files from config
    train_files = []
    for fname in train_filenames:
        if fname in file_map:
            train_files.append(file_map[fname])
        else:
            print(f"WARNING: Training file '{fname}' not found in matrix directory")
    
    # Resolve test files from config
    test_files = []
    for fname in test_filenames:
        if fname in file_map:
            test_files.append(file_map[fname])
        else:
            print(f"WARNING: Test file '{fname}' not found in matrix directory")
    
    if not train_files:
        print("ERROR: No training files resolved from config")
        sys.exit(1)
    
    if not test_files:
        print("ERROR: No test files resolved from config")
        sys.exit(1)
    
    print(f"  ✓ Training: {len(train_files)} chunks (FULL Training Set)")
    print(f"  ✓ Test: {len(test_files)} chunks (Stratified Test Set)")
    print(f"  ✓ Optuna used: {optuna_count} chunks (hyperparameter tuning only)")
    print("  Note: Training on FULL set, not the optuna subset")
    
    # Train model and calculate unbiased threshold from training prevalence
    print("\n[4/5] Training model...")
    final_model, optimal_threshold = final_training(best_params.copy(), train_files, y_all)
    
    # Evaluate without test set leakage
    print("\n[5/5] Evaluating model...")
    train_metrics = final_test(final_model, test_files, y_all, optimal_threshold)
    
    # Save model
    model_path = MODELS_DIR / f"xgboost_{TARGET_ANTIBIOTIC}_final_v2.json"
    
    try:
        final_model.save_model(str(model_path))
        print(f"\n✓ Model saved: {model_path}")
        
        # TIMESTAMP BACKUP
        ts = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
        backup_model_path = MODELS_DIR / f"xgboost_{TARGET_ANTIBIOTIC}_final_{ts}.json"
        shutil.copy2(model_path, backup_model_path)
        print(f"✓ Timestamped Backup Model saved successfully: {backup_model_path.name} in {MODELS_DIR}")
        
        # Save threshold to the antibiotic-specific config.
        # This script is the SINGLE writer of the operating threshold:
        # 06_evaluation.py now only REPORTS Youden's J and never overwrites the
        # config (removing the previous test-set data leakage + write conflict).
        antibiotic_config['evaluation'] = {
            'optimal_threshold': float(round(float(optimal_threshold), 4)),
            'threshold_type': 'Dynamic_Instance_Weighting (0.5 — per-chunk neg/pos ratio applied to DMatrix)'
        }

        # Preserve the auto-generated comment header (leading '#' lines written
        # by 04_optimization.py) so repeated runs stay idempotent and do not
        # silently strip the provenance banner.
        header_lines = []
        try:
            with open(antibiotic_config_path, 'r', encoding='utf-8') as hf:
                for line in hf:
                    if line.startswith('#') or line.strip() == '':
                        header_lines.append(line)
                    else:
                        break
        except Exception:
            header_lines = []

        with open(antibiotic_config_path, 'w', encoding='utf-8') as f:
            if header_lines:
                f.writelines(header_lines)
            yaml.dump(antibiotic_config, f, default_flow_style=False, sort_keys=False)

        print(f"✓ Unbiased Threshold saved to config: {antibiotic_config_path.name}")

    except Exception as e:
        print(f"ERROR: Failed to save model or config: {e}")
        sys.exit(1)

    # ------------------------------------------------------------------------
    # MLOps: write models/{organism}/{antibiotic}/manifest.json (model card).
    # "Best model" selection can use these metrics instead of guessing from
    # timestamps / fragile _final_v2 naming (SCALE_MLOPS_PLAN.md §7.2).
    # Best-effort — never break a successful training run.
    # ------------------------------------------------------------------------
    try:
        organism = config.get('project', {}).get('organism', 'unknown')
        run_id = rm.make_run_id(organism, TARGET_ANTIBIOTIC)
        manifest = {
            "run_id": run_id,
            "organism": organism,
            "antibiotic": TARGET_ANTIBIOTIC,
            "model_file": model_path.name,
            "metrics": train_metrics,
            "params": best_params,
            "threshold": float(optimal_threshold),
            "threshold_type": "Dynamic_Instance_Weighting (0.5)",
            "data_split_hash": rm.hash_files([str(f) for f in train_files]),
            "git_commit": rm.git_commit_hash(),
            "git_dirty": rm.git_is_dirty(),
            "created_at": datetime.datetime.now(datetime.timezone.utc).isoformat(),
        }
        if rm.write_json(MODELS_DIR / "manifest.json", manifest):
            print(f"✓ Model manifest written: {(MODELS_DIR / 'manifest.json')}")
    except Exception as e:
        print(f"⚠ Could not write model manifest: {e}")

    print("\n" + "=" * 80)
    print("TRAINING COMPLETE")
    print("=" * 80)


# ============================================================================
# SCRIPT ENTRY POINT
# ============================================================================
if __name__ == "__main__":
    # Global guard: report any unhandled exception with a traceback and exit
    # non-zero so a crash mid-training cannot leave a half-written model that a
    # downstream step silently consumes.
    import traceback
    try:
        main()
    except Exception as e:
        print(f"\nFATAL ERROR: {e}")
        traceback.print_exc()
        sys.exit(1)

